/**
 * Writes subject-centred pin crops to public/poses/pin/.
 *
 *   node scripts/gen-pin-crops.mjs
 *
 * Every pose photo is 3:2 landscape with Katie small and low in a wide room, and
 * she is left of centre in most of them. A pin template that crops a wide band
 * out of that gets the room, not her. Recomposing once, here, means every
 * template downstream can assume she is horizontally centred and only ever has
 * to solve for vertical.
 *
 * Two rules, both load-bearing:
 *   - never trim more than MAX_TRIM of the width, or the pose itself starts to go
 *   - never trim into her: the window must contain the whole subject
 * If both cannot hold at once, containment wins and the crop stays wider.
 *
 * Re-run after adding or replacing a pose photo. Cheap and idempotent.
 */
import { readdirSync, mkdirSync, existsSync, writeFileSync } from 'node:fs';
import sharp from 'sharp';

const SRC = 'public/poses';
const OUT = 'public/poses/pin';
const MAX_TRIM = 0.16;

/**
 * Katie's horizontal extent, as [left, right] pixel columns.
 *
 * She reads against this room as neutral-dark (black leggings, hair) or
 * neutral-bright (the white tee). The cream wall is warm — a channel spread over
 * 20 — so it never counts as bright-neutral, and the wood floor and plinth are
 * too warm to count as dark. Measuring the whole subject rather than just the
 * dark mass matters: centring on leg mass alone pushes her head out of frame in
 * the folded poses.
 */
async function subjectExtent(file) {
  const { data, info } = await sharp(file).raw().toBuffer({ resolveWithObject: true });
  const { width: W, height: H, channels: C } = info;
  const cols = new Array(W).fill(0);
  for (let y = (H * 0.1) | 0; y < ((H * 0.95) | 0); y++) {
    for (let x = 0; x < W; x++) {
      const i = (y * W + x) * C;
      const r = data[i], g = data[i + 1], b = data[i + 2];
      const mx = Math.max(r, g, b);
      const spread = mx - Math.min(r, g, b);
      if ((mx < 72 && spread < 26) || (mx > 195 && spread < 14)) cols[x]++;
    }
  }
  // 5% of the busiest column. Deliberately generous: at 15% the measure starts
  // dropping thin limbs — Dragon's extent collapses from 12–93% to 17–53% and
  // the crop would cut her head off. Over-including a little wall costs a
  // slightly off-centre composition; under-including costs a headless pin.
  const floor = Math.max(...cols) * 0.05;
  let L = 0, R = W - 1;
  while (L < W && cols[L] < floor) L++;
  while (R > 0 && cols[R] < floor) R--;
  return { W, H, L, R };
}

if (!existsSync(OUT)) mkdirSync(OUT, { recursive: true });

const files = readdirSync(SRC).filter((f) => f.endsWith('.jpg'));
const frames = {};
let done = 0;
for (const file of files) {
  const src = `${SRC}/${file}`;
  const { W, H, L, R } = await subjectExtent(src);
  const c = (L + R) / 2;

  let w = Math.round(Math.min(W, Math.max(2 * Math.min(c, W - c), W * (1 - MAX_TRIM))));
  let left = Math.max(0, Math.min(W - w, Math.round(c - w / 2)));
  if (left > L) left = Math.max(0, L);
  if (left + w < R) left = Math.min(W - w, R - w);

  if (!(L >= left && R <= left + w)) {
    throw new Error(`${file}: recompose would clip the subject — check the photo`);
  }

  await sharp(src)
    .extract({ left, top: 0, width: w, height: H })
    .jpeg({ quality: 86, mozjpeg: true })
    .toFile(`${OUT}/${file}`);

  const slug = file.replace('.jpg', '');
  // What a template actually gets to keep. `aspect` is the crop's own ratio;
  // `span` is how much of that width Katie occupies. Together they decide
  // whether a portrait template can hold her — see src/lib/pinInventory.ts.
  frames[slug] = {
    aspect: Number((w / H).toFixed(3)),
    span: Number(((R - L) / w).toFixed(3)),
  };

  console.log(
    `  ${slug.padEnd(22)} subject ${((c / W) * 100).toFixed(0)}%` +
    ` → ${(((c - left) / w) * 100).toFixed(0)}%   trimmed ${(((W - w) / W) * 100).toFixed(0).padStart(2)}%` +
    `   span ${(frames[slug].span * 100).toFixed(0)}%`,
  );
  done++;
}

const header = `// GENERATED by scripts/gen-pin-crops.mjs — do not edit by hand.
//
// One row per pose photo in public/poses/pin/, which is the subject-centred crop
// every pin template reads.
//
//   aspect — the crop's width / height
//   span   — how much of that width Katie occupies, 0–1
//
// A portrait template keeps \`targetAspect / aspect\` of the width. If that is
// less than \`span\`, the crop cuts into her, and the template is not eligible
// for that pose. src/lib/pinInventory.ts does the arithmetic; nothing here is a
// judgement call.

export type PoseFrame = { aspect: number; span: number };

export const POSE_FRAMES: Record<string, PoseFrame> = ${JSON.stringify(frames, null, 2)
  .replace(/"([a-z0-9-]+)":/g, "'$1':")
  .replace(/"/g, "'")};
`;
writeFileSync('src/data/poseFrames.ts', header);

console.log(`\n${done} pin crops written to ${OUT}/`);
console.log('measurements written to src/data/poseFrames.ts');
