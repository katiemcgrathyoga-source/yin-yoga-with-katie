/**
 * Measures how tall an Immersive photograph can be for each pose.
 *
 *   node scripts/gen-immersive-heights.mjs           # measure and report
 *   node scripts/gen-immersive-heights.mjs --write   # write src/data/poseTall.ts
 *
 * WHY THIS IS NOT poseFrames.ts
 * poseFrames measures the *tight* crop in public/poses/pin/, which is what the
 * landscape bands read. Immersive doesn't read that file — it wants as much of
 * the frame as it can get, and the untrimmed 1400×933 in public/poses/ has
 * noticeably more room at the sides. Measuring the tight crop said only four
 * poses could carry a tall photograph; measuring the frame Immersive actually
 * uses tells a different story, and that difference is the whole point.
 *
 * THE ARITHMETIC
 * A band 1000px wide and H tall keeps (1000/H)/1.5 of a 3:2 frame's width. Katie
 * must fit inside that, so the tallest band that keeps her whole is
 *
 *     H = 1000 / (1.5 × span)
 *
 * capped at 1500, which is the whole pin — full bleed, the version Katie picked
 * out of the set.
 *
 * Subject extent uses the same measurement as gen-pin-crops.mjs: neutral-dark or
 * neutral-bright pixels, with a 5% column floor. That floor is load-bearing —
 * raising it drops thin limbs and starts cropping heads.
 */
import { readdirSync, existsSync, writeFileSync } from 'node:fs';
import sharp from 'sharp';

const WEB = 'public/poses';
const WRITE = process.argv.includes('--write');
/** Below this a photograph cannot reach the type, so Immersive isn't offered. */
const FLOOR = 1000;

async function subjectSpan(file) {
  const { data, info } = await sharp(file).resize({ width: 1400 }).raw().toBuffer({ resolveWithObject: true });
  const { width: W, height: H, channels: C } = info;
  const cols = new Array(W).fill(0);
  for (let y = (H * 0.1) | 0; y < ((H * 0.95) | 0); y++) {
    for (let x = 0; x < W; x++) {
      const i = (y * W + x) * C;
      const r = data[i], g = data[i + 1], b = data[i + 2];
      const mx = Math.max(r, g, b);
      const spread = mx - Math.min(r, g, b);
      if ((mx < 72 && spread < 26) || (mx > 195 && spread < 14)) cols[x]++;
    }
  }
  const floor = Math.max(...cols) * 0.05;
  let L = 0, R = W - 1;
  while (L < W && cols[L] < floor) L++;
  while (R > 0 && cols[R] < floor) R--;
  return (R - L) / W;
}

const slugs = readdirSync(WEB)
  .filter((f) => f.endsWith('.jpg'))
  .map((f) => f.replace('.jpg', ''))
  .sort();

const rows = [];
for (const slug of slugs) {
  const file = `${WEB}/${slug}.jpg`;
  if (!existsSync(file)) continue;
  const { width, height } = await sharp(file).metadata();
  const span = await subjectSpan(file);
  // The measurement assumes a 3:2 frame; anything else is cropped already and
  // the arithmetic below would overstate how much room there is.
  const aspect = width / height;
  const h = Math.min(1500, Math.round(1000 / (aspect * span)));
  rows.push({ slug, span, aspect, h });
}

rows.sort((a, b) => b.h - a.h);
const full = rows.filter((r) => r.h >= 1500).length;
const tall = rows.filter((r) => r.h >= FLOOR && r.h < 1500).length;
const out = rows.filter((r) => r.h < FLOOR);

console.log(`${rows.length} photographs measured against the untrimmed frame\n`);
console.log(`  ${full}  full bleed (1500)`);
console.log(`  ${tall}  tall enough for type over the photograph (${FLOOR}-1499)`);
console.log(`  ${out.length}  too wide — these use Panel instead\n`);
for (const r of rows) {
  const mark = r.h >= 1500 ? 'FULL' : r.h >= FLOOR ? 'tall' : '  — ';
  console.log(`  ${mark}  ${String(r.h).padStart(4)}  span ${r.span.toFixed(3)}  ${r.slug}`);
}

if (WRITE) {
  const body = rows
    .slice()
    .sort((a, b) => a.slug.localeCompare(b.slug))
    .map((r) => `  '${r.slug}': ${r.h},`)
    .join('\n');
  writeFileSync(
    'src/data/poseTall.ts',
    `// GENERATED by scripts/gen-immersive-heights.mjs — do not edit by hand.
//
// The tallest full-width photograph each pose can carry in the Immersive
// template without losing an end of her. 1500 means full bleed.
//
// Measured against the untrimmed 1400×933 frame in public/poses/, which is what
// Immersive reads — not the tight crop in public/poses/pin/ that poseFrames.ts
// describes. The two disagree, and this is the one that matters here.

/** Below this the photograph can't reach the type, and Panel takes the pose. */
export const IMMERSIVE_FLOOR = ${FLOOR};

export const POSE_TALL: Record<string, number> = {
${body}
};

/** How tall Immersive's photograph may be, or 0 if this pose can't carry one. */
export const immersiveHeight = (slug: string): number => {
  const h = POSE_TALL[slug];
  return h !== undefined && h >= IMMERSIVE_FLOOR ? h : 0;
};
`,
  );
  console.log('\nsrc/data/poseTall.ts written');
}
